function ladder(k) {
  var f = FAM[k] || ['charges'], m = MS[f[0]], e = f[1] || '', out = [];
  for (var r = 1; r <= 10; r++) out.push({ pot: r * 5, rank: r, text: fill(A[k][1], r), add: m[r - 1].replace(/\{E\}/g, e).replace(/\{N\}/g, A[k][0]) });
  return { fam: f[0], famName: FAM_NAME[f[0]], el: e, steps: out };
}
